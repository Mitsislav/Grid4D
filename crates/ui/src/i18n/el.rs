//! The Greek table: (English, Greek) pairs sorted by the English text (byte
//! order), so a lookup is a binary search. The English text is the key
//! everywhere the interface calls `tr`; a test keeps this table complete.

/// The Greek for `english`, if there is one.
pub(super) fn lookup(english: &str) -> Option<&'static str> {
    TABLE
        .binary_search_by(|&(key, _)| key.cmp(english))
        .ok()
        .map(|index| TABLE[index].1)
}

